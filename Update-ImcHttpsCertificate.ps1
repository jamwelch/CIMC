function Get-ImcRedactedText {
    param([AllowNull()][string]$Text)
    if ([string]::IsNullOrWhiteSpace($Text)) { return $Text }
    $out = $Text
    $out = [regex]::Replace($out, '(?is)-----BEGIN [^-]*PRIVATE KEY-----.*?-----END [^-]*PRIVATE KEY-----', '[REDACTED-PRIVATE-KEY]')
    $out = [regex]::Replace($out, '(?is)-----BEGIN CERTIFICATE-----.*?-----END CERTIFICATE-----', '[REDACTED-CERTIFICATE]')
    $out = [regex]::Replace($out, '(?i)(pwd\s*=\s*|password\s*[:=]\s*)\S+', '$1[REDACTED]')
    return $out
}

function Write-ImcOpLog {
    param(
        [Parameter(Mandatory = $true)][string]$Message,
        [ValidateSet('INFO', 'WARN', 'ERROR', 'SKIP')][string]$Level = 'INFO',
        [string]$LogPath
    )
    $line = '{0:o} [{1}] {2}' -f (Get-Date), $Level, (Get-ImcRedactedText -Text $Message)
    if ($LogPath) {
        Add-Content -LiteralPath $LogPath -Value $line -Encoding utf8
    }
    switch ($Level) {
        'WARN'  { Write-Warning $Message }
        'ERROR' { Write-Error -Message $Message -ErrorAction Continue }
        'SKIP'  { Write-Warning $Message }
        default { Write-Information $line }
    }
}

function Test-ImcHostIdentity {
    param([string]$Value)
    if ([string]::IsNullOrWhiteSpace($Value)) { return $false }
    $trimmed = $Value.Trim()
    $parsed = $null
    if ([System.Net.IPAddress]::TryParse($trimmed, [ref]$parsed)) { return $true }
    # Hostname / FQDN: labels of letters, digits, hyphen; no scheme, path, or spaces.
    if ($trimmed -match '[:/\\\s]') { return $false }
    return [bool]($trimmed -match '^(?=.{1,253}$)[A-Za-z0-9](?:[A-Za-z0-9\-]{0,61}[A-Za-z0-9])?(?:\.[A-Za-z0-9](?:[A-Za-z0-9\-]{0,61}[A-Za-z0-9])?)*\.?$')
}

function Get-ImcCsvProperty {
    param(
        [Parameter(Mandatory = $true)]$Row,
        [Parameter(Mandatory = $true)][string[]]$Names
    )
    $map = @{}
    foreach ($p in $Row.PSObject.Properties) {
        $map[$p.Name.ToLowerInvariant()] = [string]$p.Value
    }
    foreach ($n in $Names) {
        $key = $n.ToLowerInvariant()
        if ($map.ContainsKey($key) -and -not [string]::IsNullOrWhiteSpace($map[$key])) {
            return $map[$key].Trim()
        }
    }
    return $null
}

function ConvertFrom-ImcFirmwareString {
    param([string]$Version)
    if ([string]::IsNullOrWhiteSpace($Version)) { return $null }
    $v = $Version.Trim()
    if ($v -match '^(\d+)\.(\d+)\((\d+)') {
        return [version]::new([int]$Matches[1], [int]$Matches[2], [int]$Matches[3])
    }
    if ($v -match '^(\d+)\.(\d+)\.(\d+)') {
        return [version]::new([int]$Matches[1], [int]$Matches[2], [int]$Matches[3])
    }
    if ($v -match '^(\d+)\.(\d+)$') {
        return [version]::new([int]$Matches[1], [int]$Matches[2], 0)
    }
    return $null
}


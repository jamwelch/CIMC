function Get-ImcTargetList {
    param(
        [string]$CsvPath,
        [string]$ImcAddress,
        [string]$LogPath
    )
    $targets = [System.Collections.Generic.List[object]]::new()

    if ($CsvPath) {
        if ($ImcAddress) {
            Write-ImcOpLog -LogPath $LogPath -Level WARN -Message 'Both -CsvPath and -ImcAddress were supplied. CSV wins; -ImcAddress is ignored.'
        }
        $resolved = $ExecutionContext.SessionState.Path.GetUnresolvedProviderPathFromPSPath($CsvPath)
        if (-not (Test-Path -LiteralPath $resolved -PathType Leaf)) {
            throw "CSV file not found: $resolved"
        }
        $rowIndex = 0
        $imported = @(Import-Csv -LiteralPath $resolved)
        if ($imported.Count -eq 0) {
            throw "CSV '$resolved' has no data rows."
        }
        foreach ($row in $imported) {
            $rowIndex++
            $addr = Get-ImcCsvProperty -Row $row -Names @('ImcAddress', 'Address', 'IP', 'IPv4', 'CIMC', 'CimcAddress', 'Host', 'Name')
            $hostName = Get-ImcCsvProperty -Row $row -Names @('Hostname', 'FQDN', 'DnsName', 'ExpectedName')
            if (-not $addr -and $hostName -and (Test-ImcHostIdentity -Value $hostName)) {
                $addr = $hostName
            }
            if ([string]::IsNullOrWhiteSpace($addr)) {
                $reason = "CSV row $rowIndex skipped: empty address."
                Write-ImcOpLog -LogPath $LogPath -Level SKIP -Message $reason
                $targets.Add([pscustomobject]@{
                    ImcAddress      = ''
                    Hostname        = $hostName
                    CertificatePath = Get-ImcCsvProperty -Row $row -Names @('CertificatePath', 'CertPath')
                    PrivateKeyPath  = Get-ImcCsvProperty -Row $row -Names @('PrivateKeyPath', 'KeyPath')
                    ExpectedName    = Get-ImcCsvProperty -Row $row -Names @('ExpectedName', 'Hostname', 'FQDN')
                    Source          = "csv:$rowIndex"
                    SkipReason      = $reason
                })
                continue
            }
            if (-not (Test-ImcHostIdentity -Value $addr)) {
                $reason = "CSV row $rowIndex skipped: '$addr' is not a valid IP or FQDN."
                Write-ImcOpLog -LogPath $LogPath -Level SKIP -Message $reason
                $targets.Add([pscustomobject]@{
                    ImcAddress      = $addr
                    Hostname        = $hostName
                    CertificatePath = Get-ImcCsvProperty -Row $row -Names @('CertificatePath', 'CertPath')
                    PrivateKeyPath  = Get-ImcCsvProperty -Row $row -Names @('PrivateKeyPath', 'KeyPath')
                    ExpectedName    = Get-ImcCsvProperty -Row $row -Names @('ExpectedName', 'Hostname', 'FQDN')
                    Source          = "csv:$rowIndex"
                    SkipReason      = $reason
                })
                continue
            }
            $targets.Add([pscustomobject]@{
                ImcAddress      = $addr.Trim().TrimEnd('.')
                Hostname        = $hostName
                CertificatePath = Get-ImcCsvProperty -Row $row -Names @('CertificatePath', 'CertPath')
                PrivateKeyPath  = Get-ImcCsvProperty -Row $row -Names @('PrivateKeyPath', 'KeyPath')
                ExpectedName    = Get-ImcCsvProperty -Row $row -Names @('ExpectedName')
                Source          = "csv:$rowIndex"
                SkipReason      = $null
            })
        }
        return $targets
    }

    if ([string]::IsNullOrWhiteSpace($ImcAddress)) {
        throw 'Supply -ImcAddress for a single host or -CsvPath for a list. If both are supplied, CSV wins.'
    }
    if (-not (Test-ImcHostIdentity -Value $ImcAddress)) {
        throw "ImcAddress '$ImcAddress' is not a valid IP or FQDN."
    }
    $targets.Add([pscustomobject]@{
        ImcAddress      = $ImcAddress.Trim().TrimEnd('.')
        Hostname        = $null
        CertificatePath = $null
        PrivateKeyPath  = $null
        ExpectedName    = $null
        Source          = 'param'
        SkipReason      = $null
    })
    return $targets
}

function Test-ImcPrivateKeyFile {
    param(
        [Parameter(Mandatory = $true)][string]$Path,
        [string]$LogPath
    )
    if (-not (Test-Path -LiteralPath $Path -PathType Leaf)) {
        throw "Private key file not found: $Path"
    }
    $ext = [System.IO.Path]::GetExtension($Path)
    if ($ext -match '\.(p12|pfx)$') {
        throw "PKCS #12 ($ext) is not a CIMC upload format. Convert to PEM on the workstation (openssl pkcs12) and pass the PEM path. This script does not convert PKCS #12."
    }
    if (($IsLinux -or $IsMacOS) -and (Get-Item -LiteralPath $Path).PSObject.Properties['UnixFileMode']) {
        $mode = (Get-Item -LiteralPath $Path).UnixFileMode
        if ($mode -band [System.IO.UnixFileMode]::OtherRead) {
            throw "Private key '$Path' is world-readable. Restrict permissions (chmod 600) before Path B import. Key bytes were not printed."
        }
    }
    $header = (Get-Content -LiteralPath $Path -TotalCount 1 -ErrorAction Stop)
    if ($header -notmatch '^\s*-----BEGIN (RSA |EC |ENCRYPTED )?PRIVATE KEY-----') {
        throw "Private key file does not look like a PEM private key (header check only; key bytes were not printed)."
    }
    if ($header -match 'ENCRYPTED') {
        throw 'Encrypted private keys are not documented for IMC paste/upload. Decrypt to an unencrypted PEM on the workstation first. Key bytes were not printed.'
    }
    Write-ImcOpLog -LogPath $LogPath -Message "Private key file present at path '$Path' (bytes not printed)."
}

function Test-ImcCertificatePreflight {
    param(
        [Parameter(Mandatory = $true)][string]$Path,
        [string]$ExpectedName,
        [string]$LogPath
    )
    if (-not (Test-Path -LiteralPath $Path -PathType Leaf)) {
        throw "Certificate file not found: $Path"
    }
    $ext = [System.IO.Path]::GetExtension($Path)
    if ($ext -match '\.(p12|pfx)$') {
        throw "PKCS #12 ($ext) is not a CIMC upload format. Convert to PEM (.pem/.crt/.cer) on the workstation before running. This script does not convert PKCS #12."
    }
    $openssl = Get-Command openssl -ErrorAction SilentlyContinue
    if (-not $openssl) {
        throw "openssl was not found on PATH. Install OpenSSL to preflight the certificate (openssl x509 -text -noout -in <file>), then re-run."
    }
    $text = & openssl x509 -text -noout -in $Path 2>&1 | Out-String
    if ($LASTEXITCODE -ne 0) {
        throw "openssl x509 failed for '$Path'. Confirm the file is a PEM/DER X.509 certificate. Output was not copied into the report."
    }
    $beginCount = @(Select-String -LiteralPath $Path -Pattern '-----BEGIN CERTIFICATE-----' -SimpleMatch).Count
    if ($beginCount -gt 1) {
        Write-ImcOpLog -LogPath $LogPath -Level WARN -Message "Certificate file contains $beginCount PEM blocks. CIMC HTTPS docs show a single server cert; concatenated intermediates are lab-proven on some 4.1.2+ systems only, not a Cisco contract. openssl preflight inspects the first (leaf) cert."
    }

    $notBefore = $null
    $notAfter = $null
    if ($text -match 'Not Before\s*:\s*(.+)') { $null = [datetime]::TryParse($Matches[1].Trim(), [ref]$notBefore) }
    if ($text -match 'Not After\s*:\s*(.+)') { $null = [datetime]::TryParse($Matches[1].Trim(), [ref]$notAfter) }
    $now = Get-Date
    if ($notAfter -and $notAfter -lt $now) {
        throw "This certificate expired on $($notAfter.ToString('yyyy-MM-dd')). It is no longer valid and will be rejected by clients, causing connection failures. It must be renewed and replaced immediately."
    }
    if ($notBefore -and $notBefore -gt $now) {
        Write-ImcOpLog -LogPath $LogPath -Level WARN -Message "This certificate is not yet valid. Its validity period begins on $($notBefore.ToString('yyyy-MM-dd')). Check IMC NTP/clock before installing."
    }

    $sigLine = if ($text -match 'Signature Algorithm\s*:\s*(\S+)') { $Matches[1] } else { '' }
    if ($sigLine -match '(?i)md5|sha1') {
        throw "The certificate is signed with the insecure algorithm '$sigLine'. This makes it vulnerable to collision attacks, potentially allowing for certificate forgery. It must be re-issued using a signature based on the SHA-2 family (e.g. sha256WithRSAEncryption)."
    }

    $pubAlg = if ($text -match 'Public Key Algorithm\s*:\s*(\S+)') { $Matches[1] } else { '' }
    if ($text -match 'Public-Key:\s*\((\d+)\s*bit\)') {
        $bits = [int]$Matches[1]
        if ($pubAlg -match '(?i)rsa' -and $bits -lt 2048) {
            throw "The certificate's public key is cryptographically weak (RSA, $bits). Keys of this strength are vulnerable to factorization or discrete logarithm attacks. The certificate should be re-issued using at least an RSA 2048-bit key or an ECDSA key on a P-256 (or higher) curve."
        }
    }
    $weakEc = @(
        'secp112r1', 'secp112r2', 'secp128r1', 'secp128r2', 'secp160k1', 'secp160r1', 'secp160r2',
        'secp192k1', 'secp192r1', 'prime192v1', 'secp224k1', 'secp224r1', 'P-192', 'P-224', 'nid-X9-62-prime192v1'
    )
    if ($text -match 'ASN1 OID\s*:\s*(\S+)' -or $text -match 'NIST CURVE\s*:\s*(\S+)' -or $text -match 'Named Curve\s*:\s*(\S+)') {
        $curve = $Matches[1]
        foreach ($w in $weakEc) {
            if ($curve -eq $w -or $curve -match "(?i)^$([regex]::Escape($w))$") {
                throw "The certificate's public key is cryptographically weak (EC, $curve). Keys of this strength are vulnerable to factorization or discrete logarithm attacks. The certificate should be re-issued using at least an RSA 2048-bit key or an ECDSA key on a P-256 (or higher) curve."
            }
        }
    }

    $subject = if ($text -match 'Subject:\s*(.+)') { $Matches[1].Trim() } else { '' }
    $issuer = if ($text -match 'Issuer:\s*(.+)') { $Matches[1].Trim() } else { '' }
    if ($subject -and $issuer -and $subject -eq $issuer) {
        Write-ImcOpLog -LogPath $LogPath -Level WARN -Message 'This is a self-signed certificate. Ensure this is intentional and only used for development, testing, or internal services where trust is explicitly configured. Self-signed certificates should never be used for public-facing production systems as they will not be trusted by browsers or standard clients.'
    }

    $names = [System.Collections.Generic.List[string]]::new()
    if ($subject -match 'CN\s*=\s*([^,/]+)') { $names.Add($Matches[1].Trim()) | Out-Null }
    [regex]::Matches($text, 'DNS:([^\s,]+)') | ForEach-Object { $names.Add($_.Groups[1].Value) | Out-Null }
    [regex]::Matches($text, 'IP Address:([^\s,]+)') | ForEach-Object { $names.Add($_.Groups[1].Value) | Out-Null }
    if ($ExpectedName) {
        $want = $ExpectedName.Trim().TrimEnd('.')
        $ok = $false
        foreach ($n in $names) {
            if ($n.Trim().TrimEnd('.') -eq $want) { $ok = $true; break }
            if ($n.StartsWith('*.') -and $want.Contains('.') -and $want.Substring($want.IndexOf('.') + 1) -eq $n.Substring(2).TrimEnd('.')) { $ok = $true; break }
        }
        if (-not $ok) {
            throw "Certificate CN/SAN does not include ExpectedName '$ExpectedName'. Installing it will make browsers and tools fail hostname checks."
        }
    }

    $cn = if ($subject -match 'CN\s*=\s*([^,/]+)') { $Matches[1].Trim() } else { '' }
    Write-ImcOpLog -LogPath $LogPath -Message ("Certificate preflight passed for '{0}' (CN='{1}', notAfter={2:yyyy-MM-dd}, signature={3}). PEM bytes were not printed." -f $Path, $cn, $notAfter, $sigLine)
    return [pscustomobject]@{
        CommonName        = $cn
        Issuer            = $issuer
        ValidFrom         = $notBefore
        ValidTo           = $notAfter
        SignatureAlgorithm = $sigLine
        SelfSigned        = [bool]($subject -and $issuer -and $subject -eq $issuer)
    }
}

function Test-ImcLeafKeyPair {
    param(
        [string]$CertificatePath,
        [string]$PrivateKeyPath,
        [string]$LogPath
    )
    if (-not $CertificatePath -or -not $PrivateKeyPath) { return }
    $openssl = Get-Command openssl -ErrorAction SilentlyContinue
    if (-not $openssl) { return }
    $certPub = & openssl x509 -in $CertificatePath -pubkey -noout 2>$null
    $keyPub = & openssl pkey -in $PrivateKeyPath -pubout 2>$null
    if ($LASTEXITCODE -ne 0 -or [string]::IsNullOrWhiteSpace($keyPub)) {
        throw 'openssl could not derive a public key from the private key file (encrypted key, or not a key). Key bytes were not printed.'
    }
    if (($certPub -join "`n") -ne ($keyPub -join "`n")) {
        throw 'Private key does not match the leaf certificate. Activating a mismatched Path B pair can take IMC HTTPS down until recovered from CLI/serial. Key bytes were not printed.'
    }
    Write-ImcOpLog -LogPath $LogPath -Message 'Leaf certificate and private key public keys match (key bytes not printed).'
}

function Get-ImcPemFileText {
    param([Parameter(Mandatory = $true)][string]$Path)
    # Read at runtime for XML content-cert-upload. Never log the return value.
    $raw = Get-Content -LiteralPath $Path -Raw -ErrorAction Stop
    if ([string]::IsNullOrWhiteSpace($raw)) {
        throw "File '$Path' is empty."
    }
    $bytes = [System.Text.Encoding]::UTF8.GetByteCount($raw)
    if ($bytes -gt 8192) {
        Write-Warning "File '$Path' is $bytes bytes. IMC remote/paste caps are typically 8 KB (GUI paste often 5 KB). Prefer SCP/SFTP if the upload fails on size."
    }
    return $raw
}

function Get-ImcRemotePwd {
    param([System.Management.Automation.PSCredential]$ShareCredential)
    if (-not $ShareCredential) { return $null }
    # PowerTool -Pwd is a string. Value stays in memory for the cmdlet call only.
    # Do not use ConvertTo-SecureString -AsPlainText. Do not log or persist this.
    return $ShareCredential.GetNetworkCredential().Password
}

function Test-ImcLoginFailureMessage {
    param(
        [AllowNull()][string]$Message,
        [AllowNull()][string]$FullyQualifiedErrorId
    )
    $blob = '{0} {1}' -f $Message, $FullyQualifiedErrorId
    return [bool]($blob -match '(?i)authenticat|unauthorized|invalid (user|password|credential)|login failed|access denied|not authorized|\b401\b|credentials? (are|is) (invalid|incorrect)|username or password|bad credential')
}

function Read-ImcApplyCredentialToRemaining {
    param(
        [Parameter(Mandatory = $true)][string]$ImcAddress,
        [string]$LogPath
    )
    Write-Information "Login succeeded for CIMC $ImcAddress with the replacement credential (password not logged)."
    try {
        $answer = Read-Host "Use this credential for remaining CIMC hosts in this run? [Y/N]"
    }
    catch {
        Write-ImcOpLog -LogPath $LogPath -Level WARN -Message "Could not prompt to reuse the replacement credential; remaining hosts keep the previous in-memory credential."
        return $false
    }
    $yes = [bool]($answer -match '^(y|yes)$')
    $choice = if ($yes) { 'YES' } else { 'NO' }
    Write-ImcOpLog -LogPath $LogPath -Message "Operator chose $choice to reuse the replacement CIMC credential for remaining hosts (password not logged)."
    return $yes
}

function Connect-ImcTarget {
    param(
        [Parameter(Mandatory = $true)][string]$Name,
        [Parameter(Mandatory = $true)][System.Management.Automation.PSCredential]$Credential
    )
    # InvalidCertificateAction defaults to Ignore in PowerTool — needed during rotation.
    return Connect-Imc -Name $Name -Credential $Credential
}

function Connect-ImcTargetWithRetry {
    param(
        [Parameter(Mandatory = $true)][string]$Name,
        [Parameter(Mandatory = $true)][hashtable]$Bound,
        [string]$LogPath
    )
    $attemptCred = $Bound.Credential
    if (-not $attemptCred) {
        throw "No in-memory CIMC PSCredential is available for $Name."
    }
    $user = $attemptCred.UserName
    try {
        $session = Connect-ImcTarget -Name $Name -Credential $attemptCred
        $Bound.HostCredential = $attemptCred
        Write-ImcOpLog -LogPath $LogPath -Message "Logged on to CIMC $Name as '$user' (password held in memory only; not logged)."
        return $session
    }
    catch {
        $err = Get-ImcRedactedText -Text $_.Exception.Message
        if (-not (Test-ImcLoginFailureMessage -Message $_.Exception.Message -FullyQualifiedErrorId $_.FullyQualifiedErrorId)) {
            throw "Could not connect to CIMC ${Name}: $err"
        }
        Write-ImcOpLog -LogPath $LogPath -Level WARN -Message "CIMC login failed for $Name as user '$user': $err Password was not logged."
        $retry = Get-Credential -UserName $user -Message "CIMC login failed for $Name. Enter admin credentials for CIMC $Name."
        if (-not $retry) {
            throw "CIMC login failed for $Name and the replacement prompt was cancelled. $err"
        }
        try {
            $session = Connect-ImcTarget -Name $Name -Credential $retry
        }
        catch {
            $err2 = Get-ImcRedactedText -Text $_.Exception.Message
            Write-ImcOpLog -LogPath $LogPath -Level ERROR -Message "CIMC login retry failed for $Name as user '$($retry.UserName)': $err2 Password was not logged."
            throw "CIMC login retry failed for $Name. $err2"
        }
        Write-ImcOpLog -LogPath $LogPath -Message "Logged on to CIMC $Name as '$($retry.UserName)' after re-prompt (password held in memory only; not logged)."
        $Bound.HostCredential = $retry
        if (Read-ImcApplyCredentialToRemaining -ImcAddress $Name -LogPath $LogPath) {
            $Bound.Credential = $retry
            Write-ImcOpLog -LogPath $LogPath -Message "In-memory CIMC credential updated for remaining hosts (user '$($retry.UserName)'; password not written to disk)."
        }
        else {
            Write-ImcOpLog -LogPath $LogPath -Message "Replacement credential kept for $Name only; remaining hosts still use the previous in-memory credential."
        }
        return $session
    }
}

function Disconnect-ImcQuiet {
    try { Disconnect-Imc -ErrorAction SilentlyContinue | Out-Null } catch { }
}

function Wait-ImcReconnect {
    param(
        [Parameter(Mandatory = $true)][string]$Name,
        [Parameter(Mandatory = $true)][hashtable]$Bound,
        [int]$WaitSeconds = 90,
        [string]$LogPath
    )
    $cred = if ($Bound.ContainsKey('HostCredential') -and $Bound.HostCredential) { $Bound.HostCredential } else { $Bound.Credential }
    Write-ImcOpLog -LogPath $LogPath -Level WARN -Message "IMC HTTPS/SSH sessions are expected to drop after cert upload/activate (management-plane restart, not a host OS reboot). Waiting $WaitSeconds seconds, then reconnecting."
    Disconnect-ImcQuiet
    Start-Sleep -Seconds $WaitSeconds
    $deadline = (Get-Date).AddSeconds([Math]::Max(60, $WaitSeconds))
    $last = $null
    $authPrompted = $false
    while ((Get-Date) -lt $deadline) {
        try {
            $session = Connect-ImcTarget -Name $Name -Credential $cred
            $Bound.HostCredential = $cred
            return $session
        }
        catch {
            $last = Get-ImcRedactedText -Text $_.Exception.Message
            $isAuth = Test-ImcLoginFailureMessage -Message $_.Exception.Message -FullyQualifiedErrorId $_.FullyQualifiedErrorId
            if ($isAuth -and -not $authPrompted) {
                $authPrompted = $true
                Write-ImcOpLog -LogPath $LogPath -Level WARN -Message "Reconnect login failed for CIMC $Name as user '$($cred.UserName)': $last Password was not logged."
                $retry = Get-Credential -UserName $cred.UserName -Message "Reconnect login failed for CIMC $Name after the certificate change. Enter admin credentials for CIMC $Name."
                if (-not $retry) {
                    throw "Could not reconnect to IMC '$Name' after certificate change (login prompt cancelled). Last error: $last. Recover from CIMC CLI or serial if HTTPS stays down."
                }
                $cred = $retry
                $Bound.HostCredential = $retry
                if (Read-ImcApplyCredentialToRemaining -ImcAddress $Name -LogPath $LogPath) {
                    $Bound.Credential = $retry
                    Write-ImcOpLog -LogPath $LogPath -Message "In-memory CIMC credential updated for remaining hosts after reconnect (user '$($retry.UserName)'; password not written to disk)."
                }
                continue
            }
            Write-ImcOpLog -LogPath $LogPath -Message "Reconnect attempt failed ($last). Retrying..."
            Start-Sleep -Seconds 10
        }
    }
    throw "Could not reconnect to IMC '$Name' after certificate change. Last error: $last. Recover from CIMC CLI or serial if HTTPS stays down."
}

function Get-ImcControllerFirmwareInfo {
    $running = @(Get-ImcFirmwareRunning -ErrorAction Stop)
    $row = $running | Where-Object { $_.Type -eq 'blade-controller' -and $_.Deployment -eq 'system' } | Select-Object -First 1
    if (-not $row) {
        $row = $running | Where-Object { $_.Type -eq 'blade-controller' } | Select-Object -First 1
    }
    if (-not $row) {
        $row = $running | Where-Object { $_.Deployment -eq 'system' } | Select-Object -First 1
    }
    if (-not $row -or [string]::IsNullOrWhiteSpace([string]$row.Version)) {
        throw 'Could not parse IMC controller firmware from Get-ImcFirmwareRunning. Refusing to guess Path B on an unknown version.'
    }
    $parsed = ConvertFrom-ImcFirmwareString -Version ([string]$row.Version)
    if (-not $parsed) {
        throw "Could not parse IMC firmware string '$($row.Version)'. Refusing to guess Path A vs Path B."
    }
    return [pscustomobject]@{
        VersionString = [string]$row.Version
        Version       = $parsed
        Type          = [string]$row.Type
        Deployment    = [string]$row.Deployment
    }
}

function Get-ImcCurrentCertSummary {
    $cert = Receive-ImcCertificate -ErrorAction Stop
    return [pscustomobject]@{
        CommonName         = [string]$cert.CommonName
        IssuerCommonName   = [string]$cert.IssuerCommonName
        SerialNumber       = [string]$cert.SerialNumber
        ValidFrom          = [string]$cert.ValidFrom
        ValidTo            = [string]$cert.ValidTo
    }
}

function Add-ImcSanToSplat {
    param(
        [hashtable]$Splat,
        [string[]]$San
    )
    if (-not $San -or $San.Count -eq 0) { return }
    if ($San.Count -gt 10) {
        throw 'Cisco IMC allows at most 10 SAN entries total (email, DNS, IP, URI).'
    }
    $i = 1
    foreach ($raw in $San) {
        if ([string]::IsNullOrWhiteSpace($raw)) { continue }
        $type = $null
        $value = $null
        if ($raw -match '^(DNS|IP|EMAIL|URI)\s*:\s*(.+)$') {
            $type = $Matches[1].ToUpperInvariant()
            $value = $Matches[2].Trim()
        }
        elseif ([System.Net.IPAddress]::TryParse($raw.Trim(), [ref]([System.Net.IPAddress]$null))) {
            $type = 'IP'
            $value = $raw.Trim()
        }
        else {
            $type = 'DNS'
            $value = $raw.Trim()
        }
        $Splat["SubjectAltNameType$i"] = $type
        $Splat["SubjectAltNameValue$i"] = $value
        $i++
    }
}

function Invoke-ImcCsrGenerate {
    param(
        $Target,
        [hashtable]$Bound,
        [string]$LogPath
    )
    $cn = $Bound.CommonName
    if (-not $cn) { $cn = $Target.ExpectedName }
    if (-not $cn) { $cn = $Target.Hostname }
    if (-not $cn) { $cn = $Target.ImcAddress }
    if ($cn -match '&' -or ($Bound.OrganizationalUnit -and $Bound.OrganizationalUnit -match '&')) {
        throw "Do not use '&' in CSR Common Name or Organizational Unit (Cisco IMC restriction)."
    }
    foreach ($req in @('Organization', 'OrganizationalUnit', 'Locality', 'State', 'CountryCode')) {
        if ([string]::IsNullOrWhiteSpace($Bound[$req])) {
            throw "CsrGenerate requires -$req (Cisco.IMC New-ImcCertificateSigningRequest requires CN/O/OU/L/S/C)."
        }
    }
    Write-ImcOpLog -LogPath $LogPath -Level WARN -Message 'Set IMC time/NTP to current time before generating a CSR. A wrong IMC clock produces bad notBefore/notAfter.'
    $splat = @{
        CommonName         = $cn
        Organization       = $Bound.Organization
        OrganizationalUnit = $Bound.OrganizationalUnit
        Locality           = $Bound.Locality
        State              = $Bound.State
        CountryCode        = $Bound.CountryCode
        SignatureAlgorithm = $Bound.SignatureAlgorithm
        Force              = $true
    }
    if ($Bound.Email) { $splat.Email = $Bound.Email }
    Add-ImcSanToSplat -Splat $splat -San $Bound.SubjectAlternativeName
    if ($Bound.RemoteServer -and $Bound.RemoteFile) {
        $splat.Protocol = $Bound.RemoteProtocol
        $splat.RemoteServer = $Bound.RemoteServer
        $splat.RemoteFile = $Bound.RemoteFile
        $splat.User = $Bound.RemoteShareCredential.UserName
        $splat.Pwd = Get-ImcRemotePwd -ShareCredential $Bound.RemoteShareCredential
        Write-ImcOpLog -LogPath $LogPath -Message "Generating CSR on IMC and writing it to $($Bound.RemoteProtocol)://$($Bound.RemoteServer)/$($Bound.RemoteFile) (share password not logged)."
    }
    else {
        Write-ImcOpLog -LogPath $LogPath -Message 'Generating CSR on IMC (no remote share). Copy the CSR from the IMC GUI/CLI after this step; this script does not print CSR PEM.'
    }
    if (-not $PSCmdlet.ShouldProcess($Target.ImcAddress, "Generate HTTPS CSR (Path A) CN=$cn")) {
        return 'WhatIf: CSR generate skipped.'
    }
    New-ImcCertificateSigningRequest @splat | Out-Null
    return "CSR generated (Path A). Submit it to the CA as a server certificate, then re-run with -Method CsrUpload. CN=$cn"
}

function Invoke-ImcCsrUpload {
    param(
        $Target,
        [string]$CertificatePath,
        [hashtable]$Bound,
        [string]$LogPath
    )
    if ($Bound.RemoteServer -and $Bound.RemoteFile) {
        if (-not $PSCmdlet.ShouldProcess($Target.ImcAddress, "Path A remote-cert-upload from $($Bound.RemoteServer):$($Bound.RemoteFile)")) {
            return 'WhatIf: Path A remote upload skipped.'
        }
        $splat = @{
            AdminAction  = 'remote-cert-upload'
            Protocol     = $Bound.RemoteProtocol
            RemoteServer = $Bound.RemoteServer
            RemoteFile   = $Bound.RemoteFile
            User         = $Bound.RemoteShareCredential.UserName
            Pwd          = Get-ImcRemotePwd -ShareCredential $Bound.RemoteShareCredential
            Force        = $true
        }
        Write-ImcOpLog -LogPath $LogPath -Message 'Uploading CA-signed server certificate via remote share (Path A). Sessions will drop.'
        try {
            Send-ImcCertificate @splat | Out-Null
        }
        catch {
            Write-ImcOpLog -LogPath $LogPath -Level WARN -Message ('Send-ImcCertificate returned an error that may be the expected session drop: {0}' -f (Get-ImcRedactedText $_.Exception.Message))
        }
    }
    else {
        if (-not $CertificatePath) {
            throw 'CsrUpload requires -CertificatePath (local PEM/CRT/CER minted from THIS IMC CSR) or -RemoteServer plus -RemoteFile.'
        }
        if (-not $PSCmdlet.ShouldProcess($Target.ImcAddress, "Path A content-cert-upload from $CertificatePath")) {
            return 'WhatIf: Path A content upload skipped.'
        }
        $pem = Get-ImcPemFileText -Path $CertificatePath
        Write-ImcOpLog -LogPath $LogPath -Message 'Uploading CA-signed server certificate from local path (Path A, content-cert-upload). PEM is not logged. Sessions will drop.'
        try {
            Send-ImcCertificate -AdminAction 'content-cert-upload' -CertificateContent $pem -Force | Out-Null
        }
        catch {
            Write-ImcOpLog -LogPath $LogPath -Level WARN -Message ('Send-ImcCertificate returned an error that may be the expected session drop: {0}' -f (Get-ImcRedactedText $_.Exception.Message))
        }
    }
    Wait-ImcReconnect -Name $Target.ImcAddress -Bound $Bound -WaitSeconds $Bound.ReconnectWaitSeconds -LogPath $LogPath | Out-Null
    $after = Get-ImcCurrentCertSummary
    Write-ImcOpLog -LogPath $LogPath -Level WARN -Message 'Path A upload finished. Clients still need the issuing CA in their trust store. PowerTool Ignore-invalid-cert is not proof of browser trust.'
    return ("Path A CsrUpload complete. Current CN={0} issuer={1} validTo={2}" -f $after.CommonName, $after.IssuerCommonName, $after.ValidTo)
}

function Wait-ImcExternalUpload {
    param(
        [Parameter(Mandatory = $true)][ValidateSet('Certificate', 'PrivateKey')][string]$Kind,
        [string]$LogPath
    )
    $deadline = (Get-Date).AddMinutes(2)
    do {
        $st = if ($Kind -eq 'Certificate') { Get-ImcUploadExternalCertificate } else { Get-ImcUploadExternalPrivateKey }
        $status = [string]$st.UploadStatus
        $progress = [string]$st.UploadProgress
        Write-ImcOpLog -LogPath $LogPath -Message "Path B $Kind upload status=$status progress=$progress"
        if ($status -match '(?i)fail|error') {
            throw "Path B $Kind upload reported status '$status'."
        }
        if ($status -match '(?i)complete') { return }
        Start-Sleep -Seconds 3
    } while ((Get-Date) -lt $deadline)
    throw "Timed out waiting for Path B $Kind upload to complete."
}

function Invoke-ImcExternalImport {
    param(
        $Target,
        [string]$CertificatePath,
        [string]$PrivateKeyPath,
        [hashtable]$Bound,
        [string]$LogPath
    )
    $useRemote = $Bound.RemoteServer -and $Bound.RemoteCertificateFile -and $Bound.RemotePrivateKeyFile
    if (-not $useRemote -and (-not $CertificatePath -or -not $PrivateKeyPath)) {
        throw 'ExternalImport requires local -CertificatePath and -PrivateKeyPath, or a remote share with -RemoteServer, -RemoteCertificateFile, and -RemotePrivateKeyFile (plus local paths for openssl preflight).'
    }
    if ($useRemote -and $Bound.RemoteProtocol -notmatch '^(scp|sftp)$') {
        throw 'External private key remote upload supports SCP and SFTP only.'
    }
    if (-not $PSCmdlet.ShouldProcess($Target.ImcAddress, 'Path B upload external cert + key and activate-external-cert')) {
        return 'WhatIf: Path B upload/activate skipped.'
    }

    if ($useRemote) {
        $user = $Bound.RemoteShareCredential.UserName
        $pwd = Get-ImcRemotePwd -ShareCredential $Bound.RemoteShareCredential
        Write-ImcOpLog -LogPath $LogPath -Message "Path B remote cert upload via $($Bound.RemoteProtocol) (share password not logged)."
        Set-ImcUploadExternalCertificate -AdminAction 'remote-cert-upload' -Protocol $Bound.RemoteProtocol -RemoteServer $Bound.RemoteServer -RemoteFile $Bound.RemoteCertificateFile -User $user -Pwd $pwd -Force | Out-Null
        Wait-ImcExternalUpload -Kind Certificate -LogPath $LogPath
        Write-ImcOpLog -LogPath $LogPath -Message 'Path B remote private-key upload via SCP/SFTP (key bytes and share password not logged).'
        Set-ImcUploadExternalPrivateKey -AdminAction 'remote-cert-upload' -Protocol $Bound.RemoteProtocol -RemoteServer $Bound.RemoteServer -RemoteFile $Bound.RemotePrivateKeyFile -User $user -Pwd $pwd -Force | Out-Null
        Wait-ImcExternalUpload -Kind PrivateKey -LogPath $LogPath
    }
    else {
        $certPem = Get-ImcPemFileText -Path $CertificatePath
        $keyPem = Get-ImcPemFileText -Path $PrivateKeyPath
        Write-ImcOpLog -LogPath $LogPath -Message 'Path B content-cert-upload of external certificate from local path (PEM not logged).'
        Set-ImcUploadExternalCertificate -AdminAction 'content-cert-upload' -CertificateContent $certPem -Force | Out-Null
        Wait-ImcExternalUpload -Kind Certificate -LogPath $LogPath
        Write-ImcOpLog -LogPath $LogPath -Message 'Path B content-cert-upload of external private key from local path (key bytes not logged).'
        Set-ImcUploadExternalPrivateKey -AdminAction 'content-cert-upload' -CertificateContent $keyPem -Force | Out-Null
        Wait-ImcExternalUpload -Kind PrivateKey -LogPath $LogPath
    }

    Write-ImcOpLog -LogPath $LogPath -Level WARN -Message 'Activating external certificate (Set-ImcManagedObject adminAction=activate-external-cert). HTTPS and SSH will drop.'
    $mgmt = Get-ImcCertificateManagement
    try {
        Set-ImcManagedObject -ManagedObject $mgmt -PropertyMap @{ AdminAction = 'activate-external-cert' } -Force | Out-Null
    }
    catch {
        Write-ImcOpLog -LogPath $LogPath -Level WARN -Message ('Activate returned an error that may be the expected session drop: {0}' -f (Get-ImcRedactedText $_.Exception.Message))
    }
    Wait-ImcReconnect -Name $Target.ImcAddress -Bound $Bound -WaitSeconds $Bound.ReconnectWaitSeconds -LogPath $LogPath | Out-Null
    $after = Get-ImcCurrentCertSummary
    Write-ImcOpLog -LogPath $LogPath -Level WARN -Message 'Path B activate finished. Clients still need the issuing CA in their trust store. HTML5 KVM/vMedia drop with HTTPS; IPMI over LAN does not use this cert.'
    return ("Path B ExternalImport complete. Current CN={0} issuer={1} validTo={2}" -f $after.CommonName, $after.IssuerCommonName, $after.ValidTo)
}

function Invoke-ImcHttpsCertificateHost {
    param(
        $Target,
        [hashtable]$Bound,
        [string]$LogPath
    )
    $result = [ordered]@{
        Timestamp  = (Get-Date).ToString('o')
        ImcAddress = $Target.ImcAddress
        Hostname   = $Target.Hostname
        Firmware   = ''
        Method     = $Bound.Method
        Path       = ''
        Result     = 'Failed'
        Reason     = ''
        CommonName = ''
        ValidTo    = ''
    }
    if ($Target.SkipReason) {
        $result.Result = 'Skipped'
        $result.Reason = $Target.SkipReason
        return [pscustomobject]$result
    }

    $certPath = if ($Target.CertificatePath) { $Target.CertificatePath } else { $Bound.CertificatePath }
    $keyPath = if ($Target.PrivateKeyPath) { $Target.PrivateKeyPath } else { $Bound.PrivateKeyPath }
    $expected = $Bound.ExpectedName
    if (-not $expected) { $expected = $Target.ExpectedName }
    if (-not $expected) { $expected = $Target.Hostname }

    if ($Bound.Method -in @('CsrUpload', 'ExternalImport') -and $certPath -and -not $Bound.SkipCertificatePreflight) {
        $pre = Test-ImcCertificatePreflight -Path $certPath -ExpectedName $expected -LogPath $LogPath
        $result.CommonName = $pre.CommonName
        if ($pre.ValidTo) { $result.ValidTo = $pre.ValidTo.ToString('yyyy-MM-dd') }
    }
    elseif ($Bound.Method -in @('CsrUpload', 'ExternalImport') -and $Bound.SkipCertificatePreflight) {
        Write-ImcOpLog -LogPath $LogPath -Level WARN -Message 'SkipCertificatePreflight is set. Weak/expired certificates will not be refused by this script.'
    }
    if ($Bound.Method -eq 'ExternalImport' -and $keyPath) {
        Test-ImcPrivateKeyFile -Path $keyPath -LogPath $LogPath
        if ($certPath -and -not $Bound.SkipCertificatePreflight) {
            Test-ImcLeafKeyPair -CertificatePath $certPath -PrivateKeyPath $keyPath -LogPath $LogPath
        }
    }

    $Bound.HostCredential = $null
    $session = Connect-ImcTargetWithRetry -Name $Target.ImcAddress -Bound $Bound -LogPath $LogPath
    try {
        $fw = Get-ImcControllerFirmwareInfo
        $result.Firmware = $fw.VersionString
        Write-ImcOpLog -LogPath $LogPath -Message ("Connected to {0} firmware={1} (parsed {2})" -f $Target.ImcAddress, $fw.VersionString, $fw.Version)

        $floor = [version]'4.0.4'
        $pathBMin = [version]'4.1.2'
        if ($fw.Version -lt $floor) {
            $msg = "IMC firmware $($fw.VersionString) is below the customer floor 4.0.4."
            if ($Bound.ContinueOnOldFirmware) {
                Write-ImcOpLog -LogPath $LogPath -Level WARN -Message "$msg -ContinueOnOldFirmware is set; continuing with Path A only. Path B remains refused below 4.1.2."
            }
            else {
                $result.Result = 'Skipped'
                $result.Reason = "$msg Default is to stop this host. Re-run with -ContinueOnOldFirmware if you insist."
                return [pscustomobject]$result
            }
        }

        $current = Get-ImcCurrentCertSummary
        $result.CommonName = $current.CommonName
        $result.ValidTo = $current.ValidTo
        Write-ImcOpLog -LogPath $LogPath -Message ("Current IMC HTTPS cert CN={0} issuer={1} serial={2} validFrom={3} validTo={4}" -f $current.CommonName, $current.IssuerCommonName, $current.SerialNumber, $current.ValidFrom, $current.ValidTo)

        $pathBCapable = $fw.Version -ge $pathBMin
        $method = $Bound.Method
        if ($method -eq 'Inventory') {
            $result.Path = if ($pathBCapable) { 'A-or-B' } else { 'A' }
            $result.Result = 'Success'
            $result.Reason = if ($pathBCapable) {
                "Inventory only. Firmware $($fw.VersionString) supports Path A (CSR) and Path B (external import)."
            }
            else {
                "Inventory only. Firmware $($fw.VersionString) supports Path A (CSR) only. Path B requires 4.1.2+."
            }
            if ($PSBoundParameters.ContainsKey('WhatIf') -or $WhatIfPreference) {
                $result.Reason += ' -WhatIf: no upload.'
            }
            return [pscustomobject]$result
        }

        if ($method -eq 'ExternalImport') {
            if (-not $pathBCapable) {
                $result.Path = 'B-refused'
                $result.Result = 'Failed'
                $result.Reason = "Path B (ExternalImport) refused: firmware $($fw.VersionString) is older than 4.1.2. Use Path A (CsrGenerate / CsrUpload) on this IMC."
                return [pscustomobject]$result
            }
            $result.Path = 'B'
            $result.Reason = Invoke-ImcExternalImport -Target $Target -CertificatePath $certPath -PrivateKeyPath $keyPath -Bound $Bound -LogPath $LogPath
            $after = Get-ImcCurrentCertSummary
            $result.CommonName = $after.CommonName
            $result.ValidTo = $after.ValidTo
            $result.Result = if ($result.Reason -match '^WhatIf') { 'Skipped' } else { 'Success' }
            return [pscustomobject]$result
        }

        $result.Path = 'A'
        if ($method -eq 'CsrGenerate') {
            $result.Reason = Invoke-ImcCsrGenerate -Target $Target -Bound $Bound -LogPath $LogPath
            $result.Result = if ($result.Reason -match '^WhatIf') { 'Skipped' } else { 'Success' }
            return [pscustomobject]$result
        }
        if ($method -eq 'CsrUpload') {
            $result.Reason = Invoke-ImcCsrUpload -Target $Target -CertificatePath $certPath -Bound $Bound -LogPath $LogPath
            $after = Get-ImcCurrentCertSummary
            $result.CommonName = $after.CommonName
            $result.ValidTo = $after.ValidTo
            $result.Result = if ($result.Reason -match '^WhatIf') { 'Skipped' } else { 'Success' }
            return [pscustomobject]$result
        }
        throw "Unsupported Method '$method'."
    }
    finally {
        Disconnect-ImcQuiet
        if ($session) { $session = $null }
    }
}

# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------

$paths = Get-ImcReportPathPair -Requested $ReportPath
$reportCsv = $paths.CsvPath
$reportLog = $paths.LogPath
Write-ImcOpLog -LogPath $reportLog -Message "Report CSV: $reportCsv"
Write-ImcOpLog -LogPath $reportLog -Message "Report log: $reportLog"

if (-not $Credential) {
    $who = if ($CsvPath) {
        'CIMC admin login (prompted once, stored only in memory, reused for every CSV host)'
    }
    else {
        "CIMC admin login for $ImcAddress (stored only in memory for this run)"
    }
    $Credential = Get-Credential -Message $who
}
if (-not $Credential) {
    Write-Error 'A PSCredential is required. This script does not accept passwords as plain text and does not use ConvertTo-SecureString -AsPlainText.'
    return
}
Write-ImcOpLog -LogPath $reportLog -Message "CIMC credential held in memory as user '$($Credential.UserName)' for this run (password not logged, not written to disk)."

$needRemoteShare = $false
if ($RemoteServer -and ($RemoteFile -or $RemoteCertificateFile -or $RemotePrivateKeyFile)) { $needRemoteShare = $true }
if ($needRemoteShare -and -not $RemoteShareCredential) {
    $RemoteShareCredential = Get-Credential -Message "Credential for IMC-reachable $RemoteProtocol share $RemoteServer (not the IMC login)"
}
if ($SignatureAlgorithm -match '^(sha1|md5)$') {
    Write-Error 'SHA-1 and MD5 CSR signature algorithms are refused. Use sha256, sha384 (default), or sha512.'
    return
}

$scriptBound = @{
    Method                 = $Method
    CertificatePath        = $CertificatePath
    PrivateKeyPath         = $PrivateKeyPath
    ExpectedName           = $ExpectedName
    CommonName             = $CommonName
    Organization           = $Organization
    OrganizationalUnit     = $OrganizationalUnit
    Locality               = $Locality
    State                  = $State
    CountryCode            = $CountryCode
    Email                  = $Email
    SubjectAlternativeName = $SubjectAlternativeName
    SignatureAlgorithm     = $SignatureAlgorithm
    RemoteServer           = $RemoteServer
    RemoteFile             = $RemoteFile
    RemoteCertificateFile  = $RemoteCertificateFile
    RemotePrivateKeyFile   = $RemotePrivateKeyFile
    RemoteProtocol         = $RemoteProtocol
    RemoteShareCredential  = $RemoteShareCredential
    ReconnectWaitSeconds   = $ReconnectWaitSeconds
    ContinueOnOldFirmware  = $ContinueOnOldFirmware
    SkipCertificatePreflight = $SkipCertificatePreflight
    Credential             = $Credential
    HostCredential         = $null
}

try {
    $targets = @(Get-ImcTargetList -CsvPath $CsvPath -ImcAddress $ImcAddress -LogPath $reportLog)
}
catch {
    Write-ImcOpLog -LogPath $reportLog -Level ERROR -Message (Get-ImcRedactedText $_.Exception.Message)
    throw
}

$rows = [System.Collections.Generic.List[object]]::new()
$index = 0
foreach ($t in $targets) {
    $index++
    $label = if ($t.ImcAddress) { $t.ImcAddress } else { "(empty row $($t.Source))" }
    Write-ImcOpLog -LogPath $reportLog -Message "=== Host $index/$($targets.Count): $label Method=$Method ==="
    try {
        $row = Invoke-ImcHttpsCertificateHost -Target $t -Bound $scriptBound -LogPath $reportLog
        $rows.Add($row) | Out-Null
        Write-ImcOpLog -LogPath $reportLog -Message ("Result {0} {1}: {2}" -f $row.Result, $label, $row.Reason)
        if ($row.Result -eq 'Failed' -and $stopOnError) {
            throw "Stopping after failed CIMC '$label' because -ErrorAction Stop was used. $($row.Reason)"
        }
    }
    catch {
        $msg = Get-ImcRedactedText -Text $_.Exception.Message
        $fail = [pscustomobject]@{
            Timestamp  = (Get-Date).ToString('o')
            ImcAddress = $t.ImcAddress
            Hostname   = $t.Hostname
            Firmware   = ''
            Method     = $Method
            Path       = ''
            Result     = 'Failed'
            Reason     = $msg
            CommonName = ''
            ValidTo    = ''
        }
        $rows.Add($fail) | Out-Null
        Write-ImcOpLog -LogPath $reportLog -Level ERROR -Message "Host $label failed: $msg"
        Disconnect-ImcQuiet
        if ($stopOnError) { throw }
        Write-ImcOpLog -LogPath $reportLog -Message 'Continuing with the next CIMC.'
    }
}

$rows | Export-Csv -LiteralPath $reportCsv -NoTypeInformation -Encoding utf8
$ok = @($rows | Where-Object Result -eq 'Success').Count
$bad = @($rows | Where-Object Result -eq 'Failed').Count
$skip = @($rows | Where-Object Result -eq 'Skipped').Count
Write-ImcOpLog -LogPath $reportLog -Message "Finished. Success=$ok Failed=$bad Skipped=$skip Report=$reportCsv Log=$reportLog"
Write-Output ([pscustomobject]@{
    ReportPath = $reportCsv
    LogPath    = $reportLog
    Success    = $ok
    Failed     = $bad
    Skipped    = $skip
})
